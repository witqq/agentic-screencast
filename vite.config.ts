// Сборка страницы записи.
//
// Vite нужен только здесь и только на сборке: в работающем инструменте
// страницу отдаёт собственный локальный сервер из собранных файлов,
// а сервер разработки Vite — удобство того, кто эту страницу правит.
// Поэтому собранное кладётся в `dist/record-ui`, откуда его и берёт
// `agentic-screencast record`, и именно оно уезжает потребителю.
//
// Пути относительные (`base: "./"`): страница отдаётся с корня своего
// сервера, и абсолютные ссылки на файлы сломались бы, стоит адресу
// смениться.
import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";

export default defineConfig({
  root: "src/record-ui",
  base: "./",
  plugins: [react()],
  build: {
    outDir: "../../dist/record-ui",
    emptyOutDir: true,
    // Один файл сценария и один стилей: разбивать страницу на куски
    // незачем, а меньше файлов — меньше поводов разойтись поставке
    // с тем, что сервер умеет отдавать.
    rollupOptions: { output: { entryFileNames: "[name].js", assetFileNames: "[name][extname]" } },
  },
});
