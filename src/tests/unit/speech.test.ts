// Правила чтения текста для синтеза. Место денежно опасное: строка синтеза
// входит в ключ кэша звука, и всякое её изменение заставляет синтезировать
// такт заново — у сетевого провайдера за деньги. Тесты закрепляют
// поведение, чтобы правка правил была видна как красный тест, а не как
// неожиданный счёт.
//
// Правила стали ДАННЫМИ: инструмент не знает ни одного языка, а наборы
// для русского поставляются файлами. Поэтому здесь проверяется и то,
// что истолкователь верен, и то, что поставляемые наборы дают ровно те
// строки, что давал прежний код.
import { test } from "node:test";
import assert from "node:assert/strict";
import { rulesOf, speak, speechFor, translitWord } from "../../speech.js";

const latin = rulesOf("ru-latin");
const abbr = rulesOf("ru-abbr");

test("без названных правил текст идёт как есть", () => {
  // Умолчание единственно верное: инструмент не знает языка ролика
  // и не вправе его переписывать.
  const text = "Сервис ведёт: MCP, JSON.";
  assert.equal(speechFor(undefined, text), text);
  assert.equal(speechFor("", text), text);
});

test("набор с побуквенной заменой переписывает латиницу кириллицей", () => {
  // Дефект, который это ловит: движок вроде Silero молча пропускает
  // латиницу, и «workflow идёт» звучит как «идёт».
  assert.equal(speak(latin, "workflow идёт"), "воркфлов идёт");
  assert.equal(translitWord("workflow", latin.translit!), "воркфлов");
});

test("в поставляемом наборе нет терминов чужой предметной области", () => {
  // Словарь общеупотребительных сокращений — часть инструмента; имена
  // чужих продуктов — нет. Ролик приносит свои термины сам, иначе
  // средство общего назначения читает вслух то, о чём его не просили.
  const own = { say: { "Мойра": "Мойра," } };
  assert.equal(speak(own, "Мойра ведёт"), "Мойра, ведёт");
  assert.equal(speak(latin, "Мойра ведёт"), "Мойра ведёт", "поставляемый набор её не знает");
});

test("словарь идёт раньше побуквенной замены", () => {
  // «JSON Schema» не должно распасться на «JSON» плюс остаток.
  assert.equal(speak(latin, "JSON Schema"), "джейсон-схема");
  assert.equal(speak(latin, "MCP"), "эм-си-пи");
});

test("набор для читающего латиницу движка правит только аббревиатуры", () => {
  // Переписывать латиницу целиком значило бы портить имена собственные.
  assert.equal(speak(abbr, "workflow идёт"), "workflow идёт");
  assert.equal(speak(abbr, "протокол MCP"), "протокол эм-си-пи");
});

test("адрес сайта выбрасывается целиком, а не читается наполовину", () => {
  // Здесь и живёт причина, по которой у набора есть порядок шагов
  // и различение регистра. Словарь, применённый раньше выбрасывания,
  // переписывает «mcp» внутри домена, и адрес перестаёт быть адресом:
  // вместо того чтобы исчезнуть, он произносится как «мойра-эм-си-пи точка
  // ком». Проверено исполнением — ровно это и вышло на первой редакции.
  assert.equal(speak(abbr, "Сайт example.com открыт"), "Сайт открыт");
  assert.equal(speak(abbr, "Адрес: example.com"), "Адрес:");
  assert.equal(speak(abbr, "Документация на GitHub"), "Документация на гитхабе");
});

test("наборы правил различимы: один и тот же текст читается по-разному", () => {
  const text = "workflow и MCP";
  assert.notEqual(speak(latin, text), speak(abbr, text));
});

test("несуществующий набор — отказ, называющий имя и путь", () => {
  // Молчаливое умолчание здесь было бы хуже всего: текст ушёл бы
  // в синтез непереписанным, и это слышно только в готовом ролике.
  assert.throws(() => rulesOf("нет-такого-набора"),
    /нет набора правил чтения|no speech rules/);
});

test("правила можно объявить прямо объектом, не заводя файла", () => {
  const own = { say: { "СВЧ": "эс-вэ-че" }, cleanup: [["\\s+([.!?])", "$1"]] as Array<[string, string]> };
  assert.equal(speak(own, "включите СВЧ ."), "включите эс-вэ-че.");
});
