// Разметка заголовка слайда: смена слова и пометки слова. Отдельным модулем без JSX: её
// читают и страница слайда (Slide.tsx), и разбор сценария (название части из заголовка).

/**
 * Смена слова в строке: «Built for {teams|agents|you}» — слово в скобках сменяется другими по очереди
 * и останавливается на последнем.
 */
export const ROTATE = /\{([^{}|]+(?:\|[^{}|]+)+)\}/u;
/**
 * Пометка слова прямо в заголовке, как маркером по распечатке: `==слово==` — выделение маркером,
 * `((слово))` — обводка от руки, `~~слово~~` — зачёркивание. Пометка прорисовывается, когда
 * заголовок уже встал (скрипт страницы, `marks`).
 */
export const MARK = /==([^=]+)==|\(\(([^()]+)\)\)|~~([^~]+)~~/u;
/** Заголовок без разметки смены слова и пометок: так его читают фраза по буквам и подписи. */
export const plainTitle = (text: string): string =>
  text.replace(new RegExp(MARK.source, "gu"), (_, a, b, c) => a ?? b ?? c).replace(new RegExp(ROTATE.source, "gu"), (_, w: string) => w.split("|").pop()!.trim());
