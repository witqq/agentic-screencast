// Договор о поставщике материала: то, что обязана уметь любая реализация,
// на любом языке. Здесь он выражен типами для поставляемых поставщиков;
// его внешняя, командная форма описана в README и проверяется командой
// `agentic-screencast provider-check`.
//
// Зачем он есть. Ядро собирает ролик из сцен, но НЕ знает, чем сцена
// нарисована. Слайд в две колонки, схема, снимок чужого интерфейса,
// диаграмма, страница на любом фреймворке, готовое видео — всё это
// материал, и решать, каким он бывает, должен тот, кто делает ролик,
// а не средство сборки. Прежде виды сцен были перечислены в ядре
// закрытым списком из пяти имён, и шестому виду взяться было неоткуда,
// кроме как правкой инструмента.
import type { Film, RawScene } from "../source.js";

/** Что поставщик рассказывает о своём виде сцены. */
export interface KindSpec {
  /** одна строка для читателя схемы */
  about: string;
  /** какие поля допустимы у сцены этого вида */
  fields: string[];
  /**
   * Поля, которые зритель читает в кадре, — текст, требующий перевода в варианте
   * сценария на другом языке. Остальные поля вида перечислены в `staging`:
   * стили, моменты, пути, числа. Вид, не разделивший поля, правилом перевода
   * не проверяется.
   */
  shown?: string[];
  /** поля показа и материала: перевода не требуют */
  staging?: string[];
  /**
   * Без чего сцену собрать нельзя. Группа из нескольких имён — «хотя бы
   * одно из»: так у величины, которую описывают либо рядом значений,
   * либо одиночным.
   */
  required: string[][];
  /**
   * Умолчания расписания для сцен этого вида: наезд, пятно, переход.
   * Ядро их не выбирает — оно только исполняет то, что назвал поставщик,
   * и то, что поверх назвала сама сцена.
   */
  effects?: Record<string, unknown>;
  /**
   * Материал берётся ГОТОВЫМ ФАЙЛОМ, названным этим полем, а не рисуется.
   * Так устроены снимок интерфейса и видеофайл: порождать нечего, надо
   * взять то, на что указала сцена.
   */
  fileField?: string;
  /** материал — видеофайл, а не страница */
  video?: boolean;
  /**
   * Сцена этого вида может обойтись без речи. Обычной сцене речь нужна:
   * ею задаётся длина, и её отсутствие — почти всегда обрыв сценария.
   * У готового видео длину задаёт сам файл, и молчаливая вставка — вещь
   * законная.
   */
  silentOk?: boolean;
  /** страница самодостаточна: сеть при рендере запрещена */
  offline?: boolean;
  /**
   * Сцена этого вида открывает главу ролика, и её название берётся из первого
   * непустого из названных полей. Так заставка главы сама называет главу для
   * полосы хода, а ядро не знает, какой вид сцены что означает.
   */
  chapterFrom?: string[];
  /**
   * В сцену этого вида камера влетает: в потоке (`flow: auto`) стык перед ней получает пролёт
   * (zoom), а не толчок. Так заставка, титр и финал читаются прибытием, а ядро не знает имён видов.
   */
  arrival?: boolean;

  /**
   * Материал движется сам: живой фон и входы у слайда, запись у видео.
   * Неподвижную сцену линтер ищет только среди того, что само не движется, —
   * у готовой страницы движение даёт лишь камера или фокус.
   */
  moving?: boolean;

  /**
   * Поля, которые страница вида НАБИРАЕТ по знаку: с какой секунды сцены и с какой обычной
   * скоростью (знаков в секунду). Страница ускоряет набор, чтобы он кончился до конца сцены;
   * `lint` называет сцену, где для этого нужно больше полутора обычных скоростей. Поле `unless`
   * выключает набор, когда у сцены задано другое появление текста.
   */
  typing?: Array<{ field: string; from: number; cps: number; unless?: string }>;

  /**
   * Вид показывает числа: `lint` требует у сцены поле `note` с источником и датой (film craft 12, 56).
   */
  numbers?: boolean;
  /**
   * Вид — карта трейлера: в ролике с ней удары, зерно и заглавные — словарь жанра, и `lint` не
   * считает их признаками шаблона.
   */
  trailer?: boolean;
  /** Поле, из которого вид берёт значки пунктов: эмодзи в нём `lint` считает признаком шаблона. */
  icons?: string;

  /**
   * Пороги приёмки кадра. Что считать годным кадром, знает тот, кто
   * его рисует: слайд разрежен и его текст читают, экран плотен —
   * от него нужно узнавание. Числа в ядре запрещали бы чужому материалу
   * быть годным по его собственным меркам.
   *
   * Ядро их не толкует, а передаёт проверке; какие имена осмысленны,
   * решает пара «поставщик и проверка».
   */
  check?: Record<string, number>;
}

/** Поставщик материала. */
export interface Provider {
  /** имя, которым его зовут в заголовке сцены до точки */
  readonly name: string;

  /** Виды сцен, которые он предлагает, и всё, что о них нужно знать. */
  kinds(): Record<string, KindSpec>;

  /**
   * Породить страницу сцены в названном каталоге и вернуть путь к ней.
   * Поставщик готовых файлов этого не умеет и не объявляет: ядро тогда
   * берёт файл из поля, названного `fileField`.
   *
   * Данные ролика приходят третьим доводом: оформление и размер кадра
   * принадлежат ролику целиком, и без них страница рисовалась бы всегда
   * в одном виде, каким бы ни был замысел.
   */
  page?(scene: RawScene, outDir: string, film: Film): string;

  /**
   * Проверить поля сцены, ничего не порождая: бросить ошибку с причиной.
   * Так `lint` ловит опечатку в значении поля до сборки тем же кодом, которым
   * поставщик потом читает сцену, а не вторым списком правил в ядре.
   */
  validate?(scene: RawScene, film: Film): void;
}
