// Поставщик готовой страницы: материал сцены — файл, который уже есть.
//
// Так снимаются интерфейсы чужих приложений: страница сохранена заранее
// (подкомандой `snapshot` или чем угодно другим, отвечающим договору
// подложки), и порождать нечего — надо взять то, на что указала сцена.
import type { KindSpec, Provider } from "./types.js";

/**
 * Поля наезда и подсветки принадлежат этому виду, а не ядру: они имеют
 * смысл ровно там, где в кадре чужой интерфейс и надо показать зрителю
 * место, о котором говорит речь.
 */
const screen: KindSpec = {
  about: "готовая страница: снимок интерфейса или любая самодостаточная вёрстка",
  fields: ["page", "target", "mustRead", "zoom", "spotFrom", "focus", "at"],
  required: [["page"]],
  fileField: "page",
  offline: true,
  // Наезд занимает первую треть сцены. Крайности пройдены обе: в секундах
  // движение укладывалось в две трети секунды и выглядело рывком,
  // растянутое на 0,8 сцены ползло шестнадцать секунд из двадцати.
  // Порог читаемости — 16 экранных пикселей, и он ниже слайдового
  // намеренно: слайд разрежен и его текст читают, а экран плотен, и от
  // него нужно узнавание. Проверено на кадрах: панель значений (16,2)
  // читается, подписи графа (12,2) — на пределе. Порог АБСОЛЮТНЫЙ,
  // а не доля высоты: кадр увеличивали ровно затем, чтобы при той же
  // разборчивости буквы в него помещалось больше макета.
  check: {
    mustReadSize: 16,
    targetShareRawMax: 0.5,
    targetShareFullMax: 1.15,
    coverShareMin: 0.85,
    targetShareMin: 0.002,
  },
  effects: {
    zoom: { from: "5%", to: "35%" },
    spot: { from: "55%", to: "100%" },
    cursor: { hidden: true, from: 0, to: 0.01, start: [-500, -500] },
    caption: { from: 9999 },
    fade: { in: 0.3, out: 0.3 },
  },
};

export const pageProvider: Provider = {
  name: "page",
  kinds: () => ({ page: screen }),
};
