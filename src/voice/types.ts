// Договор о движке голоса: то, что обязана уметь любая реализация,
// на любом языке. Здесь он выражен типами для поставляемых движков;
// его внешняя, командная форма описана в README и проверяется командой
// `agentic-screencast voice-check`.
//
// Инструмент о движках ничего не знает: он передаёт данные голоса
// целиком и получает звук. Поэтому третий параметр провайдера (темп
// у SpeechKit, число знаков в секунду у заглушки) не теряется по дороге
// и не требует правки сборщика.

/** Данные голоса целиком: движок, имя голоса и его собственные параметры. */
export type VoiceData = { engine?: string; name?: string } & Record<string, unknown>;

/** Ответ на просьбу синтезировать реплику. */
export interface SynthResult {
  /** путь к записанному файлу — тот же, что просили */
  file: string;
  /** длительность в секундах, с точностью до тысячных */
  duration: number;
  /** движок, которым сделан звук */
  engine: string;
  /** имя голоса */
  voice: string;
}

/**
 * Движок голоса.
 *
 * Этот интерфейс — внутренний, для ПОСТАВЛЯЕМЫХ движков, и он мягче
 * внешнего договора: поставляемый движок вызывается прямо, а не запуском
 * программы, поэтому «нет метода» здесь заменяет то, чем во внешнем
 * договоре служит ответ. У программы подкоманда `probe` обязательна,
 * и её отказ — нарушение: инструмент иначе не отличит «нечего сказать»
 * от «не смог сказать».
 *
 * `voices` возвращает пустой список, если голоса не перечисляются
 * (так у `piper` и системного синтеза). Отсутствующий `probe` читается
 * как «звук зависит только от текста и данных голоса» — так и есть
 * у всякого настоящего синтеза.
 */
export interface VoiceEngine {
  /** Имя движка в данных голоса. */
  readonly name: string;

  /** Список голосов; пустой — если движок их не перечисляет. */
  voices(): Promise<string[]> | string[];

  /**
   * Записать реплику в файл. Обязан отдать **WAV 48 кГц моно**:
   * из длины записи выводится длительность сцены, и сырой поток
   * или сжатый формат дадут неверное число.
   */
  synth(text: string, voice: VoiceData, out: string): Promise<SynthResult> | SynthResult;

  /**
   * Отпечаток: строка, которая меняется тогда и только тогда, когда
   * изменился бы звук при тех же тексте и данных голоса.
   *
   * Пустая строка означает «не меняется никогда» — так отвечает синтез,
   * потому что для него текст и данные голоса определяют звук полностью.
   * Непустую строку возвращает движок, у которого звук берётся снаружи:
   * записанный человеком голос при перезаписи даёт другой звук при тех же
   * тексте и данных, и без отпечатка сборка отдала бы прежнюю запись
   * из кэша, выглядя успешной.
   */
  probe?(text: string, voice: VoiceData): Promise<string> | string;

  /**
   * Пути, которые движок разрешает при нынешнем окружении. Нужны, чтобы
   * проверка «умолчания не уводят наружу» могла спросить об этом движок,
   * а не догадываться.
   */
  paths?(): Record<string, string>;
}

/** Требуемая частота дискретизации и число каналов. */
export const SAMPLE_RATE = 48000;
export const CHANNELS = 1;
