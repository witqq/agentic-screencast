// Записанный голос: движок, который не синтезирует, а находит запись.
//
// Он реализует тот же договор, что и синтез, и потому ничего не меняет
// в сборке: те же команды, тот же кэш, та же зависимость длительности
// сцены от длины реплики. Разница ровно одна и она принципиальна —
// **звук берётся снаружи**, и при перезаписи он меняется при тех же
// тексте и данных голоса. Синтез так не умеет, и весь запрос отпечатка
// в договоре заведён ради этого случая.
//
// Адресация записи — по ТЕКСТУ реплики. Следствие, которое обязано быть
// названо, а не обнаружено: две сцены с дословно одинаковой репликой
// получат одну и ту же запись. Для сценария ролика это верно — сцена
// с повторённой репликой и звучать должна одинаково.
import { createHash } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
import { durationOf, ff } from "./audio.js";
import { CHANNELS, SAMPLE_RATE, type SynthResult, type VoiceData, type VoiceEngine } from "./types.js";

/** Отказ движка записанного голоса: причина словами, а не дамп. */
export class RecordedError extends Error {
  readonly engineError = true;
}

/**
 * Хранилище записей. Задаётся данными голоса (`dir`), потому что это
 * часть внешнего контракта: тот, кто записывает, и тот, кто собирает,
 * обязаны говорить об одном каталоге. Умолчание считается от каталога
 * данных инструмента — там же, где кэш и вывод.
 */
export function storeDir(voice: VoiceData): string {
  const home = resolve(process.env.AGENTIC_SCREENCAST_HOME ?? resolve(process.cwd(), ".agentic-screencast"));
  return resolve(String(voice.dir ?? `${home}/recordings`));
}

/**
 * Имя файла записи для реплики. Хеш от текста, а не сам текст: реплика
 * это проза в несколько предложений, и она не имя файла ни в одной
 * файловой системе.
 */
export const slotFor = (text: string): string =>
  createHash("md5").update(text).digest("hex");

/** Путь к записи реплики, существует она или нет. */
export const recordingPath = (text: string, voice: VoiceData): string =>
  resolve(storeDir(voice), `${slotFor(text)}.wav`);

/**
 * Отпечаток — хеш СОДЕРЖИМОГО записи.
 *
 * Он обязан меняться тогда и только тогда, когда изменился бы звук.
 * Содержимое этому отвечает точно. Похожее неверное — отпечаток от имени
 * файла или от текста реплики: он непуст, выглядит работающим,
 * и договор формально соблюдён, но при перезаписи он НЕ меняется —
 * ключ кэша остаётся прежним, сборка отдаёт старую запись и выглядит
 * успешной. Ровно от этого отпечаток в договоре и заведён.
 *
 * Нет записи — нет и отпечатка: пустая строка. Отказывать здесь нельзя,
 * иначе сборка упадёт на вычислении ключа, не дойдя до внятного
 * сообщения о том, какой реплики не хватает.
 */
export function fingerprintOf(text: string, voice: VoiceData): string {
  const file = recordingPath(text, voice);
  if (!existsSync(file)) return "";
  return createHash("md5").update(readFileSync(file)).digest("hex");
}


/**
 * Причина отказа `ffmpeg` человеческими словами: последняя строка его
 * потока ошибок. Целиком его выводить нельзя — там десятки строк разбора
 * потока, за которыми причина теряется.
 */
function whyFfmpeg(e: unknown): string {
  const err = e as { stderr?: Buffer | string };
  const said = String(err.stderr ?? "").trim().split("\n").filter(Boolean);
  return said.length ? said[said.length - 1]! : "внешнее средство отказалось её читать";
}

export const recorded: VoiceEngine = {
  name: "recorded",

  /**
   * Голосов этот движок не перечисляет, и договор такой ответ допускает
   * (так же отвечают `say` и `piper`). Перечислять здесь нечего: «голос»
   * — это человек, который читал, а хранилище знает только слепки текстов
   * реплик. Выдавать слепки за имена голосов значило бы отвечать не на тот
   * вопрос; к тому же `voices` по договору не получает данных голоса
   * и не знает, о каком каталоге спрашивают.
   */
  voices: () => [],

  synth(text, voice, out): SynthResult {
    // Правила чтения переписывают текст для синтеза — латиницу
    // кириллицей и подобное. Человек читает вслух РЕПЛИКУ, а не
    // переписанную строку, и адрес записи считался бы от того, чего
    // он не произносил. Отказ здесь внятнее, чем «нет записи» с чужим
    // слепком в имени файла.
    if (voice.rules) {
      throw new RecordedError(
        `движок «recorded» не работает с правилами чтения (rules: ${String(voice.rules)})\n`
        + "запись адресуется текстом реплики, а правила переписывают его для синтеза");
    }
    const src = recordingPath(text, voice);
    if (!existsSync(src)) {
      // Названо всё, что нужно, чтобы починить: какой реплики не хватает,
      // куда её класть и под каким именем. Без этого читателю пришлось бы
      // угадывать правило адресации.
      const head = text.length > 60 ? `${text.slice(0, 60)}…` : text;
      throw new RecordedError(
        `нет записи реплики «${head}»\n`
        + `положите её файлом ${slotFor(text)}.wav в ${storeDir(voice)}`);
    }
    // Запись приводится к формату договора, а не принимается как есть:
    // из длины звука выводится длительность сцены, и чужая частота
    // дискретизации дала бы неверное число.
    //
    // Вход тут приносит ЧЕЛОВЕК, а не программа: положить в хранилище
    // не тот файл — обычное дело, а не экзотика. Поэтому отказ внешнего
    // средства превращается в отказ движка с именем файла и причиной;
    // без этого наружу уходил дамп буфера и стек, по которым не видно
    // ни того, ни другого.
    try {
      ff(["-i", src, "-ar", String(SAMPLE_RATE), "-ac", String(CHANNELS), out]);
    } catch (e) {
      throw new RecordedError(`запись не читается: ${src}\n${whyFfmpeg(e)}`);
    }
    // Длительность обязана быть настоящим числом: из неё считается число
    // кадров сцены. Частично декодируемый файл даёт её пустой, и дальше
    // рендер падал на длине массива — далеко от причины. Измерение тоже
    // запускает постороннее средство, поэтому и его отказ идёт наружу
    // отказом движка, а не исключением.
    let duration: number;
    try {
      duration = durationOf(out);
    } catch (e) {
      throw new RecordedError(`длительность записи не измеряется: ${src}\n${whyFfmpeg(e)}`);
    }
    if (!Number.isFinite(duration) || duration <= 0) {
      throw new RecordedError(
        `у записи не определяется длительность: ${src}\n`
        + "звук повреждён или это не звук; из длины реплики считается длина сцены");
    }
    return {
      file: out,
      duration,
      engine: "recorded",
      voice: String(voice.name ?? "человек"),
    };
  },

  probe: (text, voice) => fingerprintOf(text, voice),

  // Умолчание хранилища — то, что проверка «умолчания не уводят наружу»
  // обязана видеть. Каталог, названный данными голоса, сюда не попадает:
  // его выбрал пользователь, и уводит он туда, куда попросили.
  paths: () => ({ recordings: storeDir({}) }),
};
