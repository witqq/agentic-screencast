// Почему микрофон не дался — словами, а не именем исключения.
//
// Живёт отдельным модулем, потому что нужен обоим: странице записи,
// которая это показывает, и проверке, которая это меряет. Разбор причин —
// чистая функция без браузера, поэтому проверяется прямо, а не через
// поднятый интерфейс: состояний у неё пять, и подстроить браузер под
// каждое дороже, чем спросить у самой функции.
//
// Различать причины обязательно: они требуют разных действий. «Запрещено»
// чинится разрешением в браузере, «не найден» — проводом, «не запустился»
// — доступом на уровне системы или чужой программой, держащей микрофон.
// Одно общее «не получилось» не говорит читателю ничего.

/** Отказ микрофона словами. `secure` — защищённый ли контекст страницы. */
export function micReason(e: unknown, secure: boolean): string {
  const err = e as { name?: string; message?: string };
  if (!secure) {
    return "страница открыта не с localhost — браузер не даёт микрофон в незащищённом контексте";
  }
  switch (err.name) {
    case "NotAllowedError":
      return "доступ к микрофону запрещён — разрешите его для этой страницы в браузере";
    case "NotFoundError":
      return "микрофон не найден — проверьте, подключён ли он";
    case "NotReadableError":
      return "разрешение есть, но источник звука не запустился: микрофон занят другой программой "
        + "либо не выдан доступ на уровне системы";
    case "NotSupportedError":
      return "браузер отказал в записи: доступного устройства ввода нет либо запрос отклонён";
    default:
      return `микрофон недоступен: ${err.name ?? "неизвестно"} — ${err.message ?? ""}`;
  }
}
